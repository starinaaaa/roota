import type { PaymentMode } from "./model";
export function paymentInformation(mode: PaymentMode | null) {
  if (mode === "live")
    return {
      title: "Онлайн-оплата",
      text: "Оплатить заказ можно на сайте через Robokassa. Стоимость изделий и доставки Ozon будет показана перед оплатой. Курьер Яндекс Доставки оплачивается покупателем отдельно в приложении после согласования в Telegram. Электронный чек придёт на почту, указанную при оформлении заказа.",
    };
  if (mode === "test")
    return {
      title: "Тестовая оплата",
      text: "Магазин работает в тестовом режиме Robokassa. Деньги не списываются, реальная покупка и отправление не создаются.",
    };
  return {
    title: "Онлайн-оплата временно недоступна",
    text: "Оплата через Robokassa сейчас отключена. Уточните возможность оформления заказа у студии.",
  };
}
